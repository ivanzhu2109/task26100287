// Package docmerge 实现协作文档的离线合并内核（RGA 风格 CRDT）。
//
// 最多 10 名作者（编号 0..9）各自在一个副本上编辑同一篇文章。
// 副本之间只交换不可变的编辑记录（Record），记录可乱序、重复到达；
// 依赖未齐的记录进入缓冲，依赖补齐后自动生效。只要两个副本已生效的
// 记录集合相同，读出的正文就逐码点一致。
//
// 正文与编辑历史只存内存；字符序列用 treap 维护，删除为墓碑标记。
// 同一缝隙的并发插入按作者编号升序排列，整段插入不互相穿插；
// 删除只作用于记录生成时实际看见并选中的字符。
//
// 本包不要求线程安全，同一副本的调用须串行执行。
